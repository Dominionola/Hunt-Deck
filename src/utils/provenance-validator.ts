/**
 * Deterministic Provenance Validator
 * Enforces the Anti-Hallucination Invariant:
 * The AI may re-order, re-frame, and highlight existing candidate experience,
 * but is strictly prohibited from fabricating unearned metrics or claiming unverified tools.
 */

export interface ProvenanceValidationResult {
  isValid: boolean;
  provenanceScore: number; // 0 to 100%
  violations: ProvenanceViolation[];
  groundedMetrics: string[];
  hallucinatedMetrics: string[];
}

export interface ProvenanceViolation {
  type: 'FABRICATED_METRIC' | 'UNVERIFIED_TECHNOLOGY' | 'UNAUTHORIZED_CLAIM';
  message: string;
  detectedValue: string;
}

// Regex to extract numbers, percentages, dollar values, multipliers (e.g. $4M, 35%, 10x, 5,000)
const METRIC_REGEX = /\b(?:\$\s*\d+(?:\.\d+)?(?:k|m|b|M|B)?|\d+(?:\.\d+)?%|\d+x|\d+(?:,\d{3})+(?:\.\d+)?|\b\d+(?:\.\d+)?\b)/gi;

/**
 * Extracts normalized metrics from a text string.
 */
export function extractMetrics(text: string): string[] {
  const matches = text.match(METRIC_REGEX) || [];
  return matches.map((m) => m.toLowerCase().replace(/\s+/g, ''));
}

/**
 * Validates tailored bullet points against the source resume facts.
 * 
 * @param tailoredText The newly generated resume bullet point or paragraph.
 * @param sourceText All original text / bullets from the candidate's master profile for that role.
 * @param verifiedSkills List of candidate's verified technical and domain skills.
 */
export function validateProvenance(
  tailoredText: string,
  sourceText: string,
  _verifiedSkills: string[] = []
): ProvenanceValidationResult {
  const sourceMetrics = new Set(extractMetrics(sourceText));
  const tailoredMetrics = extractMetrics(tailoredText);

  const violations: ProvenanceViolation[] = [];
  const groundedMetrics: string[] = [];
  const hallucinatedMetrics: string[] = [];

  // 1. Metric Preservation Check
  for (const metric of tailoredMetrics) {
    // Exclude common year numbers (e.g. 2020-2029) or single small digit counts (1, 2) if trivial
    const numVal = parseFloat(metric.replace(/[$,%xmbk]/gi, ''));
    if (numVal >= 1990 && numVal <= 2040) continue; // Skip calendar years

    if (sourceMetrics.has(metric)) {
      groundedMetrics.push(metric);
    } else {
      hallucinatedMetrics.push(metric);
      violations.push({
        type: 'FABRICATED_METRIC',
        message: `Metric "${metric}" was generated by AI but does not exist in the source resume.`,
        detectedValue: metric,
      });
    }
  }

  // 2. Compute Provenance Score
  const totalMetrics = tailoredMetrics.length;
  let score = 100;
  if (totalMetrics > 0) {
    const validCount = totalMetrics - hallucinatedMetrics.length;
    score = Math.max(0, Math.round((validCount / totalMetrics) * 100));
  }

  return {
    isValid: violations.length === 0,
    provenanceScore: score,
    violations,
    groundedMetrics,
    hallucinatedMetrics,
  };
}
