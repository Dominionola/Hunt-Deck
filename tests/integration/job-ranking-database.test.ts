import { it } from "node:test";
import assert from "node:assert/strict";
import { loadEnvConfig } from "@next/env";
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";

it("serializes concurrent listing saves and isolates compatible resume ranking in real PostgreSQL", { skip: process.env.HUNTDECK_RUN_JOB_DATABASE_TEST !== "1", timeout: 60000 }, async () => {
  loadEnvConfig(process.cwd(), true, { info() {}, error() {} });
  const local = JSON.parse(readFileSync(".local-services/migration-rehearsal-private.json", "utf8")) as { password: string; port: number; container: string };
  const rehearsal = JSON.parse(readFileSync(".local-services/migration-rehearsal-result.json", "utf8")) as { complete: boolean; database: string };
  assert.equal(local.container, "huntdeck-migration-rehearsal"); assert.equal(local.port, 55439);
  assert.equal(rehearsal.complete, true); assert.match(rehearsal.database, /^huntdeck_recovery_\d+$/);
  process.env.DATABASE_URL = `postgresql://postgres:${local.password}@127.0.0.1:55439/${rehearsal.database}?schema=public`;
  process.env.DIRECT_URL = process.env.DATABASE_URL;
  const { db } = await import("../../src/lib/db");
  const { persistIngestedJob } = await import("../../src/services/jobs/persistJob");
  const { getPersonalizedJobs } = await import("../../src/services/jobs/personalizedJobs");
  const { jobQuerySchema } = await import("../../src/lib/validations/job");
  const { getCloudflareAiConfig } = await import("../../src/services/ai/cloudflareEmbeddingService");
  const config = getCloudflareAiConfig();
  const run = randomUUID(); const userIds: string[] = []; const jobIds: string[] = [];
  const vector = Array(1024).fill(0); vector[0] = 1;
  const realFetch = globalThis.fetch; let embeddings = 0;
  globalThis.fetch = async (url, init) => {
    assert.equal(String(url), config.endpoint);
    assert.ok(String(init?.body).includes("SYNTHETIC_DATABASE_JOB_CANARY")); embeddings++;
    await new Promise((resolve) => setTimeout(resolve, 50));
    return Response.json({ result: { data: [vector] } });
  };
  try {
    const user = await db.user.create({ data: { email: `ranking-${run}@example.invalid`, name: "Synthetic ranking" } }); userIds.push(user.id);
    const resume = await db.resume.create({ data: { userId: user.id, title: "Synthetic", originalFileUrl: "scratch", extractedText: "Synthetic source", parsedData: { fullName: "Synthetic", skills: [] }, isPrimary: true } });
    await db.$executeRaw`UPDATE resumes SET "embedding1024" = ${JSON.stringify(vector)}::vector, "embeddingModel" = ${config.model}, "embeddingVersion" = ${config.version} WHERE id = ${resume.id}`;
    const posting = { title: "Synthetic Database Engineer", company: run, description: "SYNTHETIC_DATABASE_JOB_CANARY Python SQL local verification.", remoteType: "HYBRID" as const, atsPlatform: "GREENHOUSE" as const, location: "Lagos", applicationUrl: `https://example.invalid/${run}` };
    const saved = await Promise.all([persistIngestedJob(posting), persistIngestedJob(posting), persistIngestedJob(posting)]);
    jobIds.push(...new Set(saved.map((row) => row.id)));
    assert.equal(jobIds.length, 1); assert.equal(embeddings, 1); assert.equal(saved.filter((row) => row.embedded).length, 1);
    const query = jobQuerySchema.parse({ search: run });
    assert.equal((await getPersonalizedJobs(user.id, query)).items[0].semanticSimilarity, 100);
    const adjacent = await db.jobPosting.create({ data: { ...posting, title: "Adjacent Research Analyst", applicationUrl: `https://example.invalid/${run}/adjacent` } });
    jobIds.push(adjacent.id);
    const closeVector = Array(1024).fill(0); closeVector[0] = 0.99; closeVector[1] = Math.sqrt(1 - 0.99 ** 2);
    await db.$executeRaw`UPDATE job_postings SET "embedding1024" = ${JSON.stringify(closeVector)}::vector, "embeddingModel" = ${config.model}, "embeddingVersion" = ${config.version} WHERE id = ${adjacent.id}`;
    await db.profile.create({ data: { userId: user.id, targetTitles: [adjacent.title], remotePreference: "HYBRID", preferredLocations: ["Lagos"] } });
    const boosted = await getPersonalizedJobs(user.id, jobQuerySchema.parse({}));
    assert.equal(boosted.items.length, 2, "A different title must not hide a compatible opportunity");
    assert.equal(boosted.items[0].id, adjacent.id); assert.equal(boosted.items[0].matchesTargetRole, true);
    assert.equal(boosted.items[0].semanticSimilarity, 99, "The preference boost must not inflate displayed similarity");
    assert.equal(boosted.items.find((job) => job.id === saved[0].id)?.matchesTargetRole, false);
    await db.jobPosting.update({ where: { id: adjacent.id }, data: { title: "Senior Software Engineer" } });
    await db.profile.update({ where: { userId: user.id }, data: { targetTitles: ["SWE"] } });
    const aliasBoosted = await getPersonalizedJobs(user.id, query);
    assert.equal(aliasBoosted.items[0].id, adjacent.id);
    assert.equal(aliasBoosted.items[0].matchesTargetRole, true, "An accepted abbreviation must match catalog title aliases");
    assert.equal(aliasBoosted.items[0].semanticSimilarity, 99);
    const weaker = Array(1024).fill(0); weaker[0] = 0.8; weaker[1] = 0.6;
    await db.$executeRaw`UPDATE job_postings SET "embedding1024" = ${JSON.stringify(weaker)}::vector WHERE id = ${adjacent.id}`;
    assert.equal((await getPersonalizedJobs(user.id, query)).items[0].id, saved[0].id, "A title preference must not dominate substantially stronger semantic evidence");
    await db.profile.update({ where: { userId: user.id }, data: { targetTitles: ["Synthetic%"] } });
    assert.ok((await getPersonalizedJobs(user.id, query)).items.every((job) => !job.matchesTargetRole), "A literal wildcard in a title must not boost unrelated titles");
    await db.profile.update({ where: { userId: user.id }, data: { minSalary: 10000 } });
    assert.equal((await getPersonalizedJobs(user.id, query)).items.length, 0);
    await db.profile.update({ where: { userId: user.id }, data: { minSalary: 0 } });
    await db.profile.update({ where: { userId: user.id }, data: { remotePreference: "REMOTE_ONLY" } });
    assert.equal((await getPersonalizedJobs(user.id, query)).items.length, 0);
    await db.profile.update({ where: { userId: user.id }, data: { remotePreference: "HYBRID", preferredLocations: ["Other synthetic location"] } });
    assert.equal((await getPersonalizedJobs(user.id, query)).items.length, 0);
    await db.profile.update({ where: { userId: user.id }, data: { preferredLocations: ["%"] } });
    assert.equal((await getPersonalizedJobs(user.id, query)).items.length, 0, "A literal wildcard must not match arbitrary preferred locations");
    assert.equal((await getPersonalizedJobs(user.id, jobQuerySchema.parse({ location: "_" }))).items.length, 0, "A literal wildcard must not match arbitrary searched locations");
    await db.profile.update({ where: { userId: user.id }, data: { preferredLocations: ["Lagos"] } });
    await db.$executeRaw`UPDATE job_postings SET "embeddingVersion" = 'incompatible-synthetic' WHERE id = ${jobIds[0]}`;
    const isolated = await getPersonalizedJobs(user.id, query);
    assert.equal(isolated.items.length, 1); assert.equal(isolated.items[0].id, adjacent.id);
    await db.$executeRaw`UPDATE resumes SET "embeddingVersion" = 'incompatible-synthetic' WHERE id = ${resume.id}`;
    assert.equal((await getPersonalizedJobs(user.id, query)).personalization, "incompatible_resume");
    assert.equal(embeddings, 1, "Ranking must not call an AI provider");
    const identified = { ...posting, externalJobId: `external-${run}`, title: "Original synthetic role", applicationUrl: `https://example.invalid/${run}/original` };
    const original = await persistIngestedJob(identified);
    const revised = { ...identified, title: "Revised synthetic role", applicationUrl: `https://example.invalid/${run}/revised` };
    const revisions = await Promise.all([persistIngestedJob(revised), persistIngestedJob(revised)]);
    assert.ok(revisions.every((item) => item.id === original.id), "Provider identity must survive a changed title and URL");
    assert.equal(await db.jobPosting.count({ where: { company: run, externalJobId: identified.externalJobId } }), 1);
    const conflicting = await db.jobPosting.create({ data: { ...identified, title: "Conflicting synthetic role", applicationUrl: `https://example.invalid/${run}/conflict` } });
    await assert.rejects(persistIngestedJob(revised), /Ambiguous source job identity/);
    await db.jobPosting.delete({ where: { id: conflicting.id } });
    console.log("Synthetic database checks passed: concurrent deduplication; adjacent titles retained; bounded title preference boost; unchanged similarity; salary/arrangement/location filters; model isolation. No real provider requests.");
  } finally {
    globalThis.fetch = realFetch;
    // Scope cleanup to this test's generated identities; no shared tables are cleared.
    await db.user.deleteMany({ where: { id: { in: userIds } } });
    await db.jobPosting.deleteMany({ where: { OR: [{ id: { in: jobIds } }, { company: run }] } });
    await db.$disconnect();
  }
});
